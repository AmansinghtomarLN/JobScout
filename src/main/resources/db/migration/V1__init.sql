create table config_snapshot (
    id bigint generated by default as identity primary key,
    source varchar(100),
    file_id varchar(300),
    checksum varchar(64) not null,
    modified_at timestamp with time zone,
    imported_at timestamp with time zone not null,
    company_count int not null default 0
);

create table execution_run (
    id bigint generated by default as identity primary key,
    started_at timestamp with time zone not null,
    completed_at timestamp with time zone,
    trigger_type varchar(30) not null,
    config_snapshot_id bigint references config_snapshot (id),
    status varchar(30) not null,
    jobs_found int not null default 0,
    new_jobs int not null default 0,
    summary text
);

create table company_task (
    id bigint generated by default as identity primary key,
    run_id bigint not null references execution_run (id),
    company_id varchar(100) not null,
    company_name varchar(200),
    profile_id varchar(100),
    status varchar(30) not null,
    stage varchar(30),
    attempts int not null default 0,
    pages_visited int not null default 0,
    urls_discovered int not null default 0,
    jobs_extracted int not null default 0,
    new_jobs int not null default 0,
    rejected_by_date int not null default 0,
    started_at timestamp with time zone,
    completed_at timestamp with time zone,
    error_code varchar(50),
    error_message varchar(1000)
);
create index idx_task_run on company_task (run_id);
create index idx_task_company on company_task (company_id);

create table job_posting (
    id bigint generated by default as identity primary key,
    company_id varchar(100) not null,
    company_name varchar(200),
    external_job_id varchar(200),
    dedupe_key varchar(64) not null unique,
    canonical_url varchar(2000),
    title varchar(500),
    location varchar(500),
    description text,
    employment_type varchar(100),
    posted_date date,
    posted_date_raw varchar(200),
    posted_date_status varchar(20),
    current_status varchar(20) not null,
    first_seen_at timestamp with time zone not null,
    last_seen_at timestamp with time zone not null,
    last_verified_at timestamp with time zone,
    first_run_id bigint,
    last_run_id bigint
);
create index idx_job_company on job_posting (company_id);
create index idx_job_posted on job_posting (posted_date);

create table job_observation (
    id bigint generated by default as identity primary key,
    job_id bigint not null references job_posting (id),
    run_id bigint not null references execution_run (id),
    observed_at timestamp with time zone not null,
    source_posted_text varchar(200),
    raw_values text,
    search_keyword varchar(200),
    search_location varchar(200),
    posted_days int,
    constraint uq_observation unique (job_id, run_id)
);

create table execution_event (
    id bigint generated by default as identity primary key,
    task_id bigint not null references company_task (id),
    ts timestamp with time zone not null,
    level varchar(10) not null,
    stage varchar(30),
    event_code varchar(50),
    message varchar(1000)
);
create index idx_event_task on execution_event (task_id);
